-- Q31 Find the customers whose completed-order revenue is above the average completed-order revenue of all customers.

WITH customer_revenue AS (
    SELECT customers.customerid,
           SUM(orders.quantity * products.unitprice * (1 - orders.discount)) AS total_revenue
    FROM customers
    INNER JOIN orders
        ON customers.customerid = orders.customerid
    INNER JOIN products
        ON orders.productid = products.productid
    WHERE orders.status = 'Completed'
    GROUP BY customers.customerid
),
average_revenue AS (
    SELECT AVG(total_revenue) AS avg_revenue
    FROM customer_revenue
)
SELECT customerid, total_revenue
FROM customer_revenue
WHERE total_revenue > (SELECT avg_revenue FROM average_revenue)
ORDER BY total_revenue DESC;


